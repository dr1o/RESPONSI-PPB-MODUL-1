-- Hapus tabel lama jika ada (opsional untuk reset bersih)
DROP TABLE IF EXISTS loans CASCADE;
DROP TABLE IF EXISTS books CASCADE;
DROP TABLE IF EXISTS members CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS authors CASCADE;

-- 1. Tabel Authors (Penulis)
CREATE TABLE authors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  nationality VARCHAR(100) DEFAULT 'Indonesia',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabel Categories (Kategori Buku)
CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabel Books (Buku)
CREATE TABLE books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  isbn VARCHAR(50) UNIQUE,
  title VARCHAR(255) NOT NULL,
  author_id BIGINT REFERENCES authors(id) ON DELETE SET NULL,
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  total_copies INT DEFAULT 1 CHECK (total_copies >= 0),
  available_copies INT DEFAULT 1 CHECK (available_copies >= 0),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabel Members (Anggota Perpustakaan)
CREATE TABLE members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(150) UNIQUE NOT NULL,
  member_type VARCHAR(50) DEFAULT 'STUDENT',
  joined_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Tabel Loans (Peminjaman Buku)
CREATE TABLE loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT REFERENCES books(id) ON DELETE SET NULL,
  member_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
  book_title VARCHAR(255),
  member_name VARCHAR(150),
  loan_date DATE DEFAULT CURRENT_DATE,
  due_date DATE NOT NULL,
  return_date DATE,
  status VARCHAR(50) DEFAULT 'Dipinjam', -- 'Dipinjam', 'Dikembalikan', 'Terlambat'
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Matikan Row Level Security (RLS) agar REST API dapat melakukan CRUD langsung
ALTER TABLE authors DISABLE ROW LEVEL SECURITY;
ALTER TABLE categories DISABLE ROW LEVEL SECURITY;
ALTER TABLE books DISABLE ROW LEVEL SECURITY;
ALTER TABLE members DISABLE ROW LEVEL SECURITY;
ALTER TABLE loans DISABLE ROW LEVEL SECURITY;

